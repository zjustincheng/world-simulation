"""Bake Natural Earth 1:110m land GeoJSON into compact, offline map masks.
Usage: python3 scripts/build-real-maps.py /path/to/ne_110m_land.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
Natural Earth data is public domain: https://www.naturalearthdata.com/about/terms-of-use/
"""
import hashlib
import json
import math
from pathlib import Path
import sys

WIDTH, HEIGHT = 160, 100
REGIONS = {
    'earth': ('Earth', [-180, -60, 180, 80]),
    'europe': ('Europe', [-25, 33, 48, 72]),
    'asia': ('Asia', [30, -12, 150, 65]),
    'africa': ('Africa', [-20, -36, 54, 38]),
    'north-america': ('North America', [-170, 5, -50, 75]),
    'south-america': ('South America', [-85, -57, -32, 14]),
    'oceania': ('Australia & Oceania', [108, -48, 180, 0]),
}

def mercator(lat):
    return math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))

def latitude(merc):
    return math.degrees(2 * math.atan(math.exp(math.radians(merc))) - math.pi / 2)

def contains(ring, x, y):
    inside = False
    for a, b in zip(ring, ring[1:]):
        if (a[1] > y) != (b[1] > y) and x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]:
            inside = not inside
    return inside

source = Path(sys.argv[1]).read_bytes()
features = json.loads(source)['features']
polygons = []
for feature in features:
    geometry = feature['geometry']
    parts = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    for rings in parts:
        xs, ys = zip(*[(p[0], p[1]) for p in rings[0]])
        polygons.append((min(xs), min(ys), max(xs), max(ys), rings))

maps = {}
for key, (name, bounds) in REGIONS.items():
    west, south, east, north = bounds
    bottom, top = mercator(south), mercator(north)
    # Pad each view to the tile grid's aspect ratio, preserving geographic proportions.
    center_x, center_y = (west + east) / 2, (bottom + top) / 2
    span_x, span_y = east - west, top - bottom
    if span_x / span_y < WIDTH / HEIGHT:
        span_x = span_y * WIDTH / HEIGHT
    else:
        span_y = span_x * HEIGHT / WIDTH
    west, east, bottom, top = center_x - span_x / 2, center_x + span_x / 2, center_y - span_y / 2, center_y + span_y / 2
    rows = []
    for y in range(HEIGHT):
        lat = latitude(top - (y + .5) / HEIGHT * span_y)
        candidates = [p for p in polygons if p[1] <= lat <= p[3]]
        row = []
        for x in range(WIDTH):
            lon = west + (x + .5) / WIDTH * span_x
            land = any(p[0] <= lon <= p[2] and contains(p[4][0], lon, lat) and not any(contains(hole, lon, lat) for hole in p[4][1:]) for p in candidates)
            row.append(land)
        spans = []
        x = 0
        while x < WIDTH:
            if not row[x]:
                x += 1
                continue
            start = x
            while x < WIDTH and row[x]:
                x += 1
            spans.extend([start, x - start])
        rows.append(spans)
    maps[key] = {'name': name, 'bounds': [west, latitude(bottom), east, latitude(top)], 'rows': rows}

output = Path(__file__).resolve().parents[1] / 'dist' / 'real-maps.js'
output.write_text('// Generated by scripts/build-real-maps.py. Natural Earth land data, public domain.\n'
                  '// Source SHA-256: ' + hashlib.sha256(source).hexdigest() + '\n'
                  'export const REAL_MAPS = ' + json.dumps(maps, separators=(',', ':')) + ';\n')
print(f'Built {len(maps)} real-world maps: {output.stat().st_size:,} bytes')
